//! Unicode maths classes (UTR #25, `MathClass-15.txt`, as the `unicode-math-class` crate tabulates it)
//! with Typst 0.15's overrides from `typst_utils::default_math_class`. The class decides a character's
//! spacing, its default limits and whether it may stretch as a delimiter.
//!
//! The table belongs in `fe2o3_text::unicode` beside the other character properties; it sits here until
//! that lookup exists.

/// A character's maths class.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum MathClass {
	Normal,
	Alphabetic,
	Binary,
	Closing,
	Diacritic,
	Fence,
	GlyphPart,
	Large,
	Opening,
	Punctuation,
	Relation,
	Space,
	Unary,
	Vary,
	Special,
}

impl MathClass {
	/// The class by its Typst name, as `math.class("relation", ..)` takes it.
	pub fn from_name(s: &str) -> Option<Self> {
		Some(match s {
			"normal"		=> MathClass::Normal,
			"punctuation"	=> MathClass::Punctuation,
			"opening"		=> MathClass::Opening,
			"closing"		=> MathClass::Closing,
			"fence"			=> MathClass::Fence,
			"large"			=> MathClass::Large,
			"relation"		=> MathClass::Relation,
			"unary"			=> MathClass::Unary,
			"binary"		=> MathClass::Binary,
			"vary"			=> MathClass::Vary,
			_				=> return None,
		})
	}

	pub fn name(self) -> &'static str {
		match self {
			MathClass::Normal		=> "normal",
			MathClass::Alphabetic	=> "alphabetic",
			MathClass::Binary		=> "binary",
			MathClass::Closing		=> "closing",
			MathClass::Diacritic	=> "diacritic",
			MathClass::Fence		=> "fence",
			MathClass::GlyphPart	=> "glyph-part",
			MathClass::Large		=> "large",
			MathClass::Opening		=> "opening",
			MathClass::Punctuation	=> "punctuation",
			MathClass::Relation		=> "relation",
			MathClass::Space		=> "space",
			MathClass::Unary		=> "unary",
			MathClass::Vary			=> "vary",
			MathClass::Special		=> "special",
		}
	}
}

/// The class Typst gives a character: the UTR #25 class with Typst's spacing overrides.
pub fn default_math_class(c: char) -> Option<MathClass> {
	match c {
		':'										=> Some(MathClass::Relation),
		'\u{22ef}' | '\u{22f1}' | '\u{22f0}' | '\u{22ee}'	=> Some(MathClass::Normal),
		'.' | '/'								=> Some(MathClass::Normal),
		'\u{22a5}'								=> Some(MathClass::Normal),
		'\u{214b}'								=> Some(MathClass::Binary),
		'\u{23b0}' | '\u{27c5}'					=> Some(MathClass::Opening),
		'\u{23b1}' | '\u{27c6}'					=> Some(MathClass::Closing),
		'\u{27c7}'								=> Some(MathClass::Binary),
		'\u{060c}'								=> Some(MathClass::Punctuation),
		c										=> unicode_class(c),
	}
}

/// The UTR #25 class alone.
pub fn unicode_class(c: char) -> Option<MathClass> {
	let cp = c as u32;
	let i = match CLASSES.binary_search_by(|&(lo, hi, _)| {
		if hi < cp {
			std::cmp::Ordering::Less
		} else if lo > cp {
			std::cmp::Ordering::Greater
		} else {
			std::cmp::Ordering::Equal
		}
	}) {
		Ok(i)	=> i,
		Err(_)	=> return None,
	};
	CLASSES.get(i).map(|e| e.2)
}

